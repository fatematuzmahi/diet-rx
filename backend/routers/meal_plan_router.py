"""SCRUM-49: Personalized meal plan -- today's view + accepted-plan storage.

The plan itself is generated by SCRUM-48 (``/api/plans/me``, which applies the
restriction + conflict filtering first and uses the budget context). This
router adds what SCRUM-49 still needs on top of it (SRS 3.1.3.8):

    GET  /api/meal-plan/today      today's meals from the CURRENT plan
    POST /api/meal-plan/accept     the patient accepts the CURRENT plan
    GET  /api/meal-plan/accepted   the latest ACCEPTED plan, for Module 2
                                   (safety / adherence) and Module 3 (grocery)

Identity comes ONLY from the verified access token (SCRUM-44); no route takes a
patient id. A plan that needs professional review cannot be accepted
(SRS 3.1.3.6.5: never silently choose a rule).

Needs two DIET_PLAN columns:  python backend/database/apply_meal_plan_scrum49.py
"""

from __future__ import annotations

import logging
from datetime import date, datetime, timezone
from typing import Any, Dict, Optional

import oracledb
from fastapi import APIRouter, Depends, HTTPException, Query, status

from backend.core.security import Principal, require_patient
from backend.database.connection import get_connection
from backend.services import plan_service

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/meal-plan", tags=["Meal Plan"])

SETUP_HINT = (
    "Plan acceptance is not set up in this database yet. "
    "Run: python backend/database/apply_meal_plan_scrum49.py"
)


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def _require_connection():
    connection = get_connection()
    if connection is None:
        raise HTTPException(status_code=503, detail="Database connection failed")
    return connection


def _patient_pk(principal: Principal) -> int:
    try:
        return int(principal.subject)
    except (TypeError, ValueError):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication token has an invalid subject.",
        )


def _oracle_failure(error: oracledb.Error, action: str) -> HTTPException:
    logger.error("SCRUM-49 meal plan %s failed: %s", action, error)
    code = getattr(error.args[0] if error.args else None, "code", None)
    if code == 904:  # ACCEPTED_AT / ACCEPTED_BY column missing
        return HTTPException(status_code=503, detail=SETUP_HINT)
    return HTTPException(status_code=500, detail=f"Unable to {action} right now.")


def _utc_now_naive() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


def today_index(created_at: Optional[datetime], today: date, total_days: int) -> int:
    """Which day of the plan is 'today' (0-based).

    Day 1 is the day the plan was generated; after the last day the plan
    starts again from Day 1, so a 7-day plan keeps working every week.
    """
    if total_days <= 0:
        return 0
    if created_at is None:
        return 0
    start = created_at.date() if isinstance(created_at, datetime) else created_at
    offset = (today - start).days
    if offset < 0:
        return 0
    return offset % total_days


def _acceptance(cursor, patient_id: int, plan_id: int) -> Optional[datetime]:
    cursor.execute(
        "SELECT accepted_at FROM diet_plan WHERE plan_id = :plan_id AND patient_id = :patient_id",
        plan_id=plan_id,
        patient_id=patient_id,
    )
    row = cursor.fetchone()
    return row[0] if row else None


def _latest_accepted_row(cursor, patient_id: int):
    cursor.execute(
        "SELECT plan_id, accepted_at FROM diet_plan "
        "WHERE patient_id = :patient_id AND accepted_at IS NOT NULL "
        "ORDER BY accepted_at DESC, plan_id DESC",
        patient_id=patient_id,
    )
    return cursor.fetchone()


def _plan_payload(cursor, row) -> Dict[str, Any]:
    payload = plan_service.row_to_plan(cursor, row)
    payload["days"] = [d.model_dump() if hasattr(d, "model_dump") else d for d in payload.get("days", [])]
    payload["activities"] = [
        a.model_dump() if hasattr(a, "model_dump") else a for a in payload.get("activities", [])
    ]
    payload["conflicts"] = [
        c.model_dump() if hasattr(c, "model_dump") else c for c in payload.get("conflicts", [])
    ]
    return payload


# --------------------------------------------------------------------------- #
# GET /api/meal-plan/today
# --------------------------------------------------------------------------- #
@router.get("/today")
def read_today(
    client_date: Optional[date] = Query(None, description="The browser's local date (YYYY-MM-DD)."),
    principal: Principal = Depends(require_patient),
):
    patient_id = _patient_pk(principal)
    server_today = _utc_now_naive().date()
    today = client_date if client_date and abs((client_date - server_today).days) <= 1 else server_today

    connection = _require_connection()
    cursor = connection.cursor()
    try:
        row = plan_service.read_current_plan_row(cursor, patient_id)
        if row is None:
            return {"found": False, "today_date": today.isoformat()}

        plan = _plan_payload(cursor, row)
        accepted_at = _acceptance(cursor, patient_id, plan["plan_id"])
        latest = _latest_accepted_row(cursor, patient_id)
        index = today_index(plan.get("generated_at"), today, len(plan.get("days", [])))

        return {
            "found": True,
            "today_date": today.isoformat(),
            "today_index": index,
            "plan": plan,
            "accepted": accepted_at is not None,
            "accepted_at": accepted_at,
            "accepted_plan_id": int(latest[0]) if latest else None,
            "can_accept": not plan.get("requires_review", False),
        }
    except oracledb.Error as error:
        raise _oracle_failure(error, "load today's meals")
    finally:
        cursor.close()
        connection.close()


# --------------------------------------------------------------------------- #
# POST /api/meal-plan/accept
# --------------------------------------------------------------------------- #
@router.post("/accept")
def accept_current_plan(principal: Principal = Depends(require_patient)):
    patient_id = _patient_pk(principal)
    connection = _require_connection()
    cursor = connection.cursor()
    try:
        row = plan_service.read_current_plan_row(cursor, patient_id)
        if row is None:
            raise HTTPException(status_code=404, detail="You have no plan yet. Generate one first.")
        plan = plan_service.row_to_plan(cursor, row)
        if plan.get("requires_review"):
            raise HTTPException(
                status_code=409,
                detail=(
                    "This plan needs a doctor or nutritionist to review it before it can be "
                    "accepted. Please show it to a professional first."
                ),
            )

        now = _utc_now_naive()
        cursor.execute(
            "UPDATE diet_plan SET accepted_at = :accepted_at, accepted_by = :accepted_by, "
            "updated_at = :updated_at "
            "WHERE plan_id = :plan_id AND patient_id = :patient_id",
            accepted_at=now,
            accepted_by=patient_id,
            updated_at=now,
            plan_id=plan["plan_id"],
            patient_id=patient_id,
        )
        if not cursor.rowcount:
            raise HTTPException(status_code=404, detail="That plan was not found.")
        connection.commit()
        return {"accepted": True, "plan_id": plan["plan_id"], "accepted_at": now}
    except HTTPException:
        connection.rollback()
        raise
    except oracledb.Error as error:
        connection.rollback()
        raise _oracle_failure(error, "accept the plan")
    finally:
        cursor.close()
        connection.close()


# --------------------------------------------------------------------------- #
# GET /api/meal-plan/accepted  (for Module 2 and Module 3)
# --------------------------------------------------------------------------- #
@router.get("/accepted")
def read_accepted_plan(principal: Principal = Depends(require_patient)):
    patient_id = _patient_pk(principal)
    connection = _require_connection()
    cursor = connection.cursor()
    try:
        latest = _latest_accepted_row(cursor, patient_id)
        if latest is None:
            return {"found": False}
        row = plan_service.read_plan_row(cursor, int(latest[0]))
        if row is None:
            return {"found": False}
        return {"found": True, "accepted_at": latest[1], "plan": _plan_payload(cursor, row)}
    except oracledb.Error as error:
        raise _oracle_failure(error, "read your accepted plan")
    finally:
        cursor.close()
        connection.close()