"""SCRUM-48: Personalized Diet + Activity Plan endpoints (SRS 3.3.6).

Endpoints
---------
    POST /api/plans/me             generate (or regenerate) my plan
    GET  /api/plans/me             read my stored CURRENT plan
    GET  /api/plans/me/history     list my previous + current plans

Identity & ownership
--------------------
The patient is identified STRICTLY from the authenticated access token's
``subject_id`` (``Principal.subject``) with ``role == "PATIENT"``. These routes
accept NO ``patient_id`` in the path, query string or request body, so a
patient can only ever generate, read or regenerate their OWN plan. The
existing SCRUM-44 security layer is reused unchanged:

    * 401 -- missing / malformed / expired / bad-signature / wrong-purpose token.
    * 403 -- an authenticated principal that is not a PATIENT (e.g. a DOCTOR).

Plan lifecycle
--------------
SRS 3.3.6.5 requires the current accepted plan to be stored so Module 2 can
monitor adherence. Generating a plan therefore writes a new DIET_PLAN row
(plus its ACTIVITY_PLAN row) and the previous plan is kept as history with
``status = 'SUPERSEDED'``. Only one plan per patient is CURRENT at a time.

SRS 3.3.6.4 -- the plan can be regenerated after the patient changes their
goals or preferences. The request body carries OPTIONAL overrides; anything
that is not supplied falls back to the value stored in the patient's health
profile, prescriptions and budget, so a patient can regenerate without
editing their profile first.

The plan is generated by a deterministic, rule-based engine
(``backend.services.diet_generator``): no ML and no external service is
involved, and the same inputs always produce the same plan. Conflicts that
cannot be safely resolved are reported in the response and flagged with
``requires_review`` for a doctor/nutritionist instead of being guessed.
"""

