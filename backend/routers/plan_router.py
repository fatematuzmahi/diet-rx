def _require_connection():
    """Return a live Oracle connection or raise 503 (distinct from 401/403)."""
    connection = get_connection()
    if connection is None:
        raise HTTPException(status_code=503, detail="Database connection failed")
    return connection


def _patient_pk(principal: Principal) -> int:
    """Coerce the authenticated patient subject_id to the PATIENT primary key.

    Identity comes only from the verified token, never from the request. A token
    whose subject is not a valid integer id is treated as an invalid credential.
    """
    try:
        return int(principal.subject)
    except (TypeError, ValueError):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication token has an invalid subject.",
        )


def _load_patient_context(cursor, patient_id: int) -> Dict[str, Any]:
    """Read everything the generator needs from the patient's own records.

    Base fields come from PATIENT, the extended fields from HEALTH_PROFILE,
    the budget from BUDGET and the instructions from PRESCRIPTION.
    """
    cursor.execute(
        "SELECT age, gender, weight, height FROM patient WHERE patient_id = :patient_id",
        patient_id=patient_id,
    )
    patient_row = cursor.fetchone()
    age = gender = weight = height = None
    if patient_row is not None:
        age, gender, weight, height = patient_row

    cursor.execute(
        """
        SELECT conditions, allergies, activity_level, food_preference,
               goals, physical_limitations
        FROM health_profile
        WHERE patient_id = :patient_id
        """,
        patient_id=patient_id,
    )
    profile_row = cursor.fetchone()
    conditions = allergies = activity_level = food_preference = None
    goals = physical_limitations = None
    if profile_row is not None:
        (
            conditions,
            allergies,
            activity_level,
            food_preference,
            goals,
            physical_limitations,
        ) = profile_row

    cursor.execute(
        "SELECT monthly_budget FROM budget WHERE patient_id = :patient_id",
        patient_id=patient_id,
    )
    budget_row = cursor.fetchone()
    monthly_budget = budget_row[0] if budget_row is not None else None

    prescriptions = plan_service.read_prescription_rows(cursor, patient_id)

    return {
        "age": age,
        "gender": gender,
        "weight_kg": weight,
        "height_cm": height,
        "conditions": conditions,
        "allergies": allergies,
        "activity_level": activity_level,
        "food_preference": food_preference,
        "goals": goals,
        "physical_limitations": physical_limitations,
        "monthly_budget": monthly_budget,
        "prescriptions": prescriptions,
    }


def _pick(override, stored):
    """Use the request override when it is given, else the stored value."""
    if override is not None:
        return override
    return stored

@router.post("/me", response_model=PlanGenerateResponse, status_code=201)
def generate_my_plan(
    payload: Optional[PlanGenerateRequest] = None,
    principal: Principal = Depends(require_patient),
):
    """Generate a personalized meal + activity plan for the current patient.

    The plan is built from the patient's profile, prescriptions, health
    conditions, preferences, goals and budget. Optional overrides in the body
    let the patient regenerate against changed information without first
    editing the profile (SRS 3.3.6.4).

    The generated plan is stored: the new row becomes the CURRENT plan and the
    previous one is kept as SUPERSEDED history (SRS 3.3.6.5).
    """
    patient_id = _patient_pk(principal)
    request = payload or PlanGenerateRequest()

    connection = _require_connection()
    cursor = connection.cursor()
    try:
        context = _load_patient_context(cursor, patient_id)

        plan = generate_plan(
            patient_id=patient_id,
            age=context["age"],
            gender=context["gender"],
            weight_kg=context["weight_kg"],
            height_cm=context["height_cm"],
            activity_level=_pick(request.activity_level, context["activity_level"]),
            goals=_pick(request.goals, context["goals"]),
            conditions=context["conditions"],
            allergies=context["allergies"],
            physical_limitations=context["physical_limitations"],
            food_preference=_pick(request.food_preference, context["food_preference"]),
            monthly_budget=_pick(request.monthly_budget, context["monthly_budget"]),
            prescriptions=context["prescriptions"],
            days=request.days,
        )

        snapshot = {
            "goals": _pick(request.goals, context["goals"]),
            "conditions": context["conditions"],
            "allergies": context["allergies"],
            "physical_limitations": context["physical_limitations"],
            "food_preference": _pick(request.food_preference, context["food_preference"]),
            "activity_level": _pick(request.activity_level, context["activity_level"]),
            "monthly_budget": _pick(request.monthly_budget, context["monthly_budget"]),
            "days": request.days,
            "budget_notes": plan["budget_notes"],
            "notes": plan["notes"],
            "cautions": plan["cautions"],
        }

        if request.regenerate:
            # Keep the previous plan as history (SRS 3.3.6.5).
            plan_service.supersede_previous_plans(cursor, patient_id)

        plan_id = plan_service.insert_plan(
            cursor,
            patient_id,
            calorie_target=plan["calorie_target"],
            meal_plan=plan["days"],
            activity_plan=plan["activities"],
            cautions=plan["cautions"],
            restrictions_applied=plan["restrictions_applied"],
            conflicts=plan["conflicts"],
            profile_snapshot=snapshot,
        )
        connection.commit()

        row = plan_service.read_plan_row(cursor, plan_id)
        if row is None:  # pragma: no cover - defensive
            raise HTTPException(
                status_code=500, detail="The generated plan could not be read back."
            )
        return PlanGenerateResponse.model_validate(plan_service.row_to_plan(cursor, row))
    except HTTPException:
        connection.rollback()
        raise
    except oracledb.Error as error:
        connection.rollback()
        logger.error(
            "SCRUM-48 plan generation failed: %s",
            getattr(error.args[0] if error.args else None, "code", None),
        )
        raise HTTPException(
            status_code=500, detail="Unable to generate the plan right now."
        )
    finally:
        cursor.close()
        connection.close()


