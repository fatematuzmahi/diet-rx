@router.get("/me", response_model=PlanCurrentResponse)
def read_my_current_plan(principal: Principal = Depends(require_patient)):
    """Read the patient's stored CURRENT plan.

    ``found`` is False when the patient has never generated a plan; the
    remaining fields are then empty rather than missing.
    """
    patient_id = _patient_pk(principal)

    connection = _require_connection()
    cursor = connection.cursor()
    try:
        row = plan_service.read_current_plan_row(cursor, patient_id)
        if row is None:
            return PlanCurrentResponse(
                plan_id=0,
                patient_id=patient_id,
                found=False,
            )
        payload = plan_service.row_to_plan(cursor, row)
        payload["found"] = True
        return PlanCurrentResponse.model_validate(payload)
    except HTTPException:
        connection.rollback()
        raise
    except oracledb.Error as error:
        connection.rollback()
        logger.error(
            "SCRUM-48 plan read failed: %s",
            getattr(error.args[0] if error.args else None, "code", None),
        )
        raise HTTPException(
            status_code=500, detail="Unable to read the stored plan right now."
        )
    finally:
        cursor.close()
        connection.close()


