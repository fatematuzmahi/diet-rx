
"""
SCRUM-61: Create the ADMIN_USER table if it does not exist.

This script creates the table only.
It does not create an admin account or modify existing tables.
"""

import sys
from pathlib import Path

# Support running from the project root:
# python -m backend.database.apply_admin_user
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from backend.database.connection import get_connection


TABLE_EXISTS_QUERY = """
SELECT COUNT(*)
FROM user_tables
WHERE table_name = :table_name
"""

CREATE_TABLE_SQL = """
CREATE TABLE ADMIN_USER (
    ADMIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    EMAIL VARCHAR2(255) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_ADMIN_USER_EMAIL UNIQUE (EMAIL)
)
"""


def apply_admin_user_schema() -> None:
    """Create ADMIN_USER only if it does not already exist."""
    connection = get_connection()

    if connection is None:
        print("Database connection failed.")
        return

    try:
        with connection.cursor() as cursor:
            cursor.execute(
                TABLE_EXISTS_QUERY,
                table_name="ADMIN_USER",
            )
            table_exists = cursor.fetchone()[0] > 0

            if table_exists:
                print(
                    "ADMIN_USER table already exists. "
                    "No changes made."
                )
                return

            cursor.execute(CREATE_TABLE_SQL)
            connection.commit()

            print("ADMIN_USER table created successfully.")

    except Exception:
        connection.rollback()
        print("Failed to create ADMIN_USER table.")
        raise

    finally:
        connection.close()
        print("Database connection closed.")


if __name__ == "__main__":
    apply_admin_user_schema()
